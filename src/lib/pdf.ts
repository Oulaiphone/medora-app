import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { Platform, Share } from 'react-native';

import { addDays, dateKey, label, longDay, shortDate } from './dates';
import { FOOD_LABEL, adherence, dosesFor, supplyText, unitWord } from './schedule';
import type { DoseLog, Medication, Profile } from './types';

export interface SummaryOptions {
  meds: boolean;
  history: boolean;
  allergies: boolean;
  contacts: boolean;
  recipient: string;
}

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c] ?? c);

export function summaryHtml(profile: Profile, meds: Medication[], doses: DoseLog[], o: SummaryOptions): string {
  const now = new Date();
  const active = meds.filter((m) => m.active);
  const rows = active
    .map(
      (m) => `<tr><td><b>${esc(m.name)}</b><br><span class="mut">${esc(m.strength)} ${esc(unitWord(m.form, 1))}</span></td>
      <td>${m.dose} × ${m.times.map(label).join(', ')}</td><td>${esc(m.instructions)}<br><span class="mut">${FOOD_LABEL[m.food]}</span></td>
      <td>${esc(m.prescriber || '—')}</td><td>${esc(supplyText(m))}</td></tr>`,
    )
    .join('');
  let hist = '';
  if (o.history) {
    const days: string[] = [];
    for (let i = 29; i >= 0; i--) days.push(dateKey(addDays(now, -i)));
    const a = adherence(active, doses, now, 30);
    const recent = days
      .slice(-7)
      .map((d) => {
        const slots = dosesFor(active, doses, d, now);
        const cells = slots
          .map((s) => `<span class="pill ${s.status}">${esc(s.med.name)} ${label(s.time)}: ${s.status}${s.log?.reason ? ` (${esc(s.log.reason)})` : ''}</span>`)
          .join(' ');
        return `<tr><td class="nowrap">${shortDate(d)}</td><td>${cells || '<span class="mut">No doses</span>'}</td></tr>`;
      })
      .join('');
    hist = `<h2>Dose history</h2><p>Last 30 days: <b>${a.taken} of ${a.total}</b> scheduled doses recorded as taken${a.total ? ` (${Math.round((a.taken / a.total) * 100)}%)` : ''}.</p>
      <table class="hist"><tbody>${recent}</tbody></table>`;
  }
  return `<!doctype html><html><head><meta charset="utf-8"><style>
  body{font-family:-apple-system,Helvetica,Arial,sans-serif;color:#1C2B27;margin:32px;font-size:12px}
  h1{font-size:22px;margin:0;color:#1F4D40} h2{font-size:15px;margin:22px 0 8px;color:#1F4D40}
  .mut{color:#5D6B67} .top{display:flex;justify-content:space-between;align-items:flex-end;border-bottom:2px solid #2E6A55;padding-bottom:10px}
  table{width:100%;border-collapse:collapse} td,th{border-bottom:1px solid #E3E7E5;padding:7px 6px;text-align:left;vertical-align:top}
  th{font-size:11px;color:#5D6B67;text-transform:uppercase;letter-spacing:.05em}
  .box{background:#EAF4F2;border-radius:8px;padding:10px 12px;margin-top:8px}
  .pill{display:inline-block;border-radius:10px;padding:2px 7px;margin:2px;background:#E9ECEA;font-size:10.5px}
  .pill.taken{background:#E3F1EA;color:#2E6B52} .pill.skipped{background:#FBF0DC;color:#8A5A10} .pill.missed{background:#FBE7E5;color:#A83434}
  .nowrap{white-space:nowrap} .foot{margin-top:28px;color:#5D6B67;font-size:10.5px}
  </style></head><body>
  <div class="top"><div><h1>Medication summary</h1><div class="mut">${esc(profile.name || 'MedOra user')}${profile.dob ? ` · born ${esc(profile.dob)}` : ''}</div></div>
  <div class="mut">Created ${longDay(now)}<br>Prepared for ${esc(o.recipient)}</div></div>
  ${o.allergies ? `<div class="box"><b>Allergies:</b> ${profile.allergies.length ? esc(profile.allergies.join(', ')) : 'None recorded'}</div>` : ''}
  ${o.meds ? `<h2>Current medicines (${active.length})</h2><table><thead><tr><th>Medicine</th><th>When</th><th>How</th><th>Prescriber</th><th>Supply</th></tr></thead><tbody>${rows}</tbody></table>` : ''}
  ${hist}
  ${o.contacts ? `<h2>Contacts</h2><p>${profile.emergency.name ? `Emergency contact: <b>${esc(profile.emergency.name)}</b> (${esc(profile.emergency.relation)}) ${esc(profile.emergency.phone)}<br>` : ''}${profile.providers.map((p) => `${esc(p.name)}, ${esc(p.role)}, ${esc(p.org)}`).join('<br>')}${profile.pharmacy ? `<br>Pharmacy: ${esc(profile.pharmacy)}` : ''}</p>` : ''}
  <p class="foot">Generated by MedOra from information entered by the patient or their caregivers. Please confirm any changes with a healthcare professional.</p>
  </body></html>`;
}

export async function shareSummaryPdf(html: string, fileTitle: string): Promise<void> {
  if (Platform.OS === 'web') {
    await Print.printAsync({ html });
    return;
  }
  const { uri } = await Print.printToFileAsync({ html });
  if (await Sharing.isAvailableAsync()) {
    await Sharing.shareAsync(uri, { mimeType: 'application/pdf', UTI: 'com.adobe.pdf', dialogTitle: fileTitle });
  } else {
    await Share.share({ url: uri, title: fileTitle });
  }
}

export function summaryText(profile: Profile, meds: Medication[]): string {
  const lines = meds
    .filter((m) => m.active)
    .map((m) => `• ${m.name} ${m.strength}: ${m.dose} ${unitWord(m.form, m.dose)} at ${m.times.map(label).join(', ')}. ${m.instructions}.`);
  return [
    `${profile.name || 'My'} medicines (MedOra, ${longDay()}):`,
    ...lines,
    profile.allergies.length ? `Allergies: ${profile.allergies.join(', ')}` : '',
  ]
    .filter(Boolean)
    .join('\n');
}
